USE master;
GO

IF NOT EXISTS (SELECT name FROM sys.databases WHERE name = N'QuanLyDiemSV')
BEGIN
    CREATE DATABASE QuanLyDiemSV;
END
GO

USE QuanLyDiemSV;
GO

-- 1. BẢNG ROLES
IF OBJECT_ID('dbo.Roles', 'U') IS NULL
CREATE TABLE Roles (
    RoleID INT IDENTITY(1,1) PRIMARY KEY,
    RoleName NVARCHAR(50) NOT NULL,
    MoTa NVARCHAR(255) NULL
);

-- 2. BẢNG USERACCOUNTS
IF OBJECT_ID('dbo.UserAccounts', 'U') IS NULL
CREATE TABLE UserAccounts (
    UserID INT IDENTITY(1,1) PRIMARY KEY,
    Username NVARCHAR(50) NOT NULL UNIQUE,
    PasswordHash NVARCHAR(255) NOT NULL,
    RoleID INT NULL FOREIGN KEY REFERENCES Roles(RoleID) ON DELETE SET NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    NgayTao DATETIME2 NOT NULL DEFAULT GETDATE(),
    MaGV NVARCHAR(20) NULL
);

-- 3. BẢNG SESSIONS
IF OBJECT_ID('dbo.Sessions', 'U') IS NULL
CREATE TABLE Sessions (
    SessionID INT IDENTITY(1,1) PRIMARY KEY,
    UserID INT NOT NULL FOREIGN KEY REFERENCES UserAccounts(UserID) ON DELETE CASCADE,
    RefreshToken NVARCHAR(MAX) NOT NULL,
    ExpiresAt DATETIME2 NOT NULL,
    IsRevoked BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

-- 4. BẢNG CHUCNANG
IF OBJECT_ID('dbo.ChucNang', 'U') IS NULL
CREATE TABLE ChucNang (
    MaChucNang NVARCHAR(50) PRIMARY KEY,
    TenChucNang NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(255) NULL
);

-- 5. BẢNG HANHDONG
IF OBJECT_ID('dbo.HanhDong', 'U') IS NULL
CREATE TABLE HanhDong (
    MaHanhDong NVARCHAR(50) PRIMARY KEY,
    TenHanhDong NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(255) NULL
);

-- 6. BẢNG PHANQUYEN
IF OBJECT_ID('dbo.PhanQuyen', 'U') IS NULL
CREATE TABLE PhanQuyen (
    RoleID INT NOT NULL FOREIGN KEY REFERENCES Roles(RoleID) ON DELETE CASCADE,
    MaChucNang NVARCHAR(50) NOT NULL FOREIGN KEY REFERENCES ChucNang(MaChucNang) ON DELETE CASCADE,
    MaHanhDong NVARCHAR(50) NOT NULL FOREIGN KEY REFERENCES HanhDong(MaHanhDong) ON DELETE CASCADE,
    PRIMARY KEY (RoleID, MaChucNang, MaHanhDong)
);

-- 7. BẢNG PHANQUYENPHAMVI
IF OBJECT_ID('dbo.PhanQuyenPhamVi', 'U') IS NULL
CREATE TABLE PhanQuyenPhamVi (
    RoleID INT NOT NULL FOREIGN KEY REFERENCES Roles(RoleID) ON DELETE CASCADE,
    MaPhamVi NVARCHAR(50) NOT NULL,
    Module NVARCHAR(100) NOT NULL,
    [Rule] NVARCHAR(255) NULL,
    IsActive BIT NOT NULL DEFAULT 0,
    PRIMARY KEY (RoleID, MaPhamVi)
);

-- 8. BẢNG KHOA
IF OBJECT_ID('dbo.Khoa', 'U') IS NULL
CREATE TABLE Khoa (
    MaKhoa NVARCHAR(20) PRIMARY KEY,
    TenKhoa NVARCHAR(255) NOT NULL,
    NgayThanhLap DATE NULL,
    TruongKhoa NVARCHAR(100) NULL
);

-- 9. BẢNG NGANH
IF OBJECT_ID('dbo.Nganh', 'U') IS NULL
CREATE TABLE Nganh (
    MaNganh NVARCHAR(20) PRIMARY KEY,
    TenNganh NVARCHAR(255) NOT NULL,
    MaKhoa NVARCHAR(20) NULL FOREIGN KEY REFERENCES Khoa(MaKhoa)
);

-- 10. BẢNG QUYDINHTOTNGHIEP
IF OBJECT_ID('dbo.QuyDinhTotNghiep', 'U') IS NULL
CREATE TABLE QuyDinhTotNghiep (
    MaNganh NVARCHAR(20) PRIMARY KEY FOREIGN KEY REFERENCES Nganh(MaNganh) ON DELETE CASCADE,
    TongTTC INT NOT NULL DEFAULT 130,
    TCBatBuoc INT NOT NULL DEFAULT 100,
    TCTuChon INT NOT NULL DEFAULT 30,
    MinGPA FLOAT NOT NULL DEFAULT 2.0
);

-- 11. BẢNG MONHOC
IF OBJECT_ID('dbo.MonHoc', 'U') IS NULL
CREATE TABLE MonHoc (
    MaMon NVARCHAR(20) PRIMARY KEY,
    TenMon NVARCHAR(255) NOT NULL,
    SoTinChi INT NOT NULL,
    SoTietLyThuyet INT NULL,
    SoTietThucHanh INT NULL,
    MaKhoa NVARCHAR(20) NULL FOREIGN KEY REFERENCES Khoa(MaKhoa)
);

-- 12. BẢNG DIEUKIENMONHOC
IF OBJECT_ID('dbo.DieuKienMonHoc', 'U') IS NULL
CREATE TABLE DieuKienMonHoc (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    MaMon NVARCHAR(20) NULL FOREIGN KEY REFERENCES MonHoc(MaMon) ON DELETE CASCADE,
    MaMonTienQuyet NVARCHAR(20) NULL FOREIGN KEY REFERENCES MonHoc(MaMon)
);

-- 13. BẢNG KHUNGCHUONGTRINH
IF OBJECT_ID('dbo.KhungChuongTrinh', 'U') IS NULL
CREATE TABLE KhungChuongTrinh (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    MaNganh NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES Nganh(MaNganh) ON DELETE CASCADE,
    MaMon NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES MonHoc(MaMon) ON DELETE CASCADE,
    HocKyDuKien INT NOT NULL,
    LoaiMon NVARCHAR(50) NOT NULL DEFAULT N'Bắt buộc',
    CONSTRAINT UQ_Nganh_Mon UNIQUE (MaNganh, MaMon)
);

-- 14. BẢNG GIANGVIEN
IF OBJECT_ID('dbo.GiangVien', 'U') IS NULL
CREATE TABLE GiangVien (
    MaGV NVARCHAR(20) PRIMARY KEY,
    HoTen NVARCHAR(255) NOT NULL,
    NgaySinh DATE NULL,
    GioiTinh NVARCHAR(10) NULL,
    Email NVARCHAR(255) NULL,
    SDT NVARCHAR(20) NULL,
    HocVi NVARCHAR(100) NULL,
    MaKhoa NVARCHAR(20) NULL FOREIGN KEY REFERENCES Khoa(MaKhoa),
    UserID INT NULL FOREIGN KEY REFERENCES UserAccounts(UserID) ON DELETE SET NULL,
    CCCD NVARCHAR(20) NULL
);

-- 15. BẢNG HOCKY
IF OBJECT_ID('dbo.HocKy', 'U') IS NULL
CREATE TABLE HocKy (
    MaHK NVARCHAR(20) PRIMARY KEY,
    TenHK NVARCHAR(50) NOT NULL,
    NamHocBatDau INT NOT NULL,
    NamHocKetThuc INT NOT NULL
);

-- 16. BẢNG LOPHANHCHINH
IF OBJECT_ID('dbo.LopHanhChinh', 'U') IS NULL
CREATE TABLE LopHanhChinh (
    MaLop NVARCHAR(20) PRIMARY KEY,
    TenLop NVARCHAR(255) NOT NULL,
    NienKhoa NVARCHAR(50) NULL,
    MaNganh NVARCHAR(20) NULL FOREIGN KEY REFERENCES Nganh(MaNganh),
    MaGVCN NVARCHAR(20) NULL FOREIGN KEY REFERENCES GiangVien(MaGV) ON DELETE SET NULL
);

-- 17. BẢNG SINHVIEN
IF OBJECT_ID('dbo.SinhVien', 'U') IS NULL
CREATE TABLE SinhVien (
    MaSV NVARCHAR(20) PRIMARY KEY,
    HoTen NVARCHAR(255) NOT NULL,
    NgaySinh DATE NULL,
    GioiTinh NVARCHAR(10) NULL,
    DiaChi NVARCHAR(255) NULL,
    CCCD NVARCHAR(20) NULL,
    Email NVARCHAR(255) NULL,
    SDT NVARCHAR(20) NULL,
    MaLop NVARCHAR(20) NULL FOREIGN KEY REFERENCES LopHanhChinh(MaLop),
    TrangThai NVARCHAR(50) NULL DEFAULT N'Đang học',
    UserID INT NULL FOREIGN KEY REFERENCES UserAccounts(UserID) ON DELETE SET NULL
);

-- 18. BẢNG LOPHOCPHAN
IF OBJECT_ID('dbo.LopHocPhan', 'U') IS NULL
CREATE TABLE LopHocPhan (
    MaLHP NVARCHAR(20) PRIMARY KEY,
    MaMon NVARCHAR(20) NULL FOREIGN KEY REFERENCES MonHoc(MaMon),
    MaHK NVARCHAR(20) NULL FOREIGN KEY REFERENCES HocKy(MaHK),
    MaGV NVARCHAR(20) NULL FOREIGN KEY REFERENCES GiangVien(MaGV) ON DELETE SET NULL,
    TenLopHP NVARCHAR(255) NULL,
    PhongHoc NVARCHAR(50) NULL,
    SiSoToiDa INT NULL DEFAULT 40,
    TrangThai NVARCHAR(50) NULL DEFAULT N'MoDangKy',
    CauHinhDiem NVARCHAR(MAX) NULL,
    TrangThaiNhapDiem NVARCHAR(50) NULL DEFAULT N'Vui lòng nhập điểm'
);

-- 19. BẢNG KETQUAHOCTAP
IF OBJECT_ID('dbo.KetQuaHocTap', 'U') IS NULL
CREATE TABLE KetQuaHocTap (
    MaKQ INT IDENTITY(1,1) PRIMARY KEY,
    MaSV NVARCHAR(20) NULL FOREIGN KEY REFERENCES SinhVien(MaSV) ON DELETE CASCADE,
    MaLHP NVARCHAR(20) NULL FOREIGN KEY REFERENCES LopHocPhan(MaLHP) ON DELETE CASCADE,
    DiemCC FLOAT NULL,
    DiemGK FLOAT NULL,
    DiemCK FLOAT NULL,
    DiemChu NVARCHAR(5) NULL,
    GhiChu NVARCHAR(255) NULL,
    DiemThiLan1 FLOAT NULL,
    DiemThiLan2 FLOAT NULL,
    DiemTongKet FLOAT NULL,
    ChiTietDiemQT NVARCHAR(MAX) NULL
);

-- 20. BẢNG DONKHIEUNAI
IF OBJECT_ID('dbo.DonKhieuNai', 'U') IS NULL
CREATE TABLE DonKhieuNai (
    MaKN INT IDENTITY(1,1) PRIMARY KEY,
    MaSV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES SinhVien(MaSV) ON DELETE CASCADE,
    MaLHP NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES LopHocPhan(MaLHP) ON DELETE CASCADE,
    LyDo NVARCHAR(MAX) NOT NULL,
    LoaiDiem NVARCHAR(50) NOT NULL DEFAULT N'quatrinh',
    NgayGui DATETIME2 NOT NULL DEFAULT GETDATE(),
    TrangThai NVARCHAR(50) NOT NULL DEFAULT N'pending',
    PhanHoi NVARCHAR(MAX) NULL,
    DaXem BIT NOT NULL DEFAULT 0
);

-- 21. BẢNG THONGBAO
IF OBJECT_ID('dbo.ThongBao', 'U') IS NULL
CREATE TABLE ThongBao (
    MaThongBao INT IDENTITY(1,1) PRIMARY KEY,
    MaNguoiGui NVARCHAR(20) NULL,
    MaNguoiNhan NVARCHAR(20) NULL,
    TieuDe NVARCHAR(255) NULL,
    NoiDung NVARCHAR(MAX) NULL,
    LoaiThongBao NVARCHAR(50) NULL,
    ThamChieuID NVARCHAR(50) NULL,
    NgayGui DATETIME2 NOT NULL DEFAULT GETDATE(),
    DaDoc BIT NOT NULL DEFAULT 0
);

-- 22. BẢNG NHATKYHOATDONG
IF OBJECT_ID('dbo.NhatKyHoatDong', 'U') IS NULL
CREATE TABLE NhatKyHoatDong (
    MaLog INT IDENTITY(1,1) PRIMARY KEY,
    NguoiDung NVARCHAR(100) NULL,
    ThoiGian DATETIME2 NOT NULL DEFAULT GETDATE(),
    HanhDong NVARCHAR(255) NULL,
    ChiTiet NVARCHAR(MAX) NULL,
    Loai NVARCHAR(50) NULL DEFAULT N'Thông tin'
);
GO

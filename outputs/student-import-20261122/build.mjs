import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const dir = new URL('.', import.meta.url);
const data = JSON.parse(await fs.readFile(new URL('data.json', dir), 'utf8'));
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('DanhSachSinhVien');
sheet.getRange('A1:J31').setNumberFormat('@');
sheet.getRange('A1:J31').values = data;
sheet.getRange('A1:J31').format.font.name = 'Arial';
sheet.getRange('A1:J31').format.font.size = 11;
sheet.getRange('A1:J1').format.fill = '#17365D';
sheet.getRange('A1:J1').format.font.color = '#FFFFFF';
sheet.getRange('A1:J1').format.font.bold = true;
sheet.getRange('A1:J31').format.rowHeight = 23;
for (const [col, width] of Object.entries({A:17,B:25,C:14,D:15,E:18,F:12,G:32,H:17,I:20,J:16}))
    sheet.getRange(`${col}:${col}`).format.columnWidth = width;
sheet.freezePanes.freezeRows(1);
const output = await SpreadsheetFile.exportXlsx(workbook);
await output.save(fileURLToPath(new URL('SinhVien_Moi_30_HoSo.xlsx', dir)));
const preview = await workbook.render({sheetName:'DanhSachSinhVien',range:'A1:J8',scale:1.5,format:'png'});
await fs.writeFile(new URL('preview.png',dir), new Uint8Array(await preview.arrayBuffer()));
console.log('Created 30 new student profiles');
